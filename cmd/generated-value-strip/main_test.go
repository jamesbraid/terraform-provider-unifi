package main

import (
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestStripFileRefusesAFileWithNoSchemaFunction is the guard against emptying
// a file this tool does not understand. The header is what selects a file;
// kept == 0 is what says the file it selected does not carry the one shape
// this tool exists to preserve. Stripping such a file would leave nothing
// behind rather than a schema function, and that has to be a refusal rather
// than a silent empty file.
func TestStripFileRefusesAFileWithNoSchemaFunction(t *testing.T) {
	for name, body := range map[string]string{
		"only a helper function":         "func helper() string { return \"not a schema\" }\n",
		"only a type declaration":        "type Thing struct{}\n",
		"nothing but the package clause": "",
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "surface_gen.go")
			source := "// Code generated by " + generatorHeader + " DO NOT EDIT.\n\npackage generated\n\n" + body
			if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
				t.Fatal(err)
			}

			_, _, err := stripFile(path, false, io.Discard)
			if err == nil {
				t.Fatal("stripFile() accepted a file with no schema function")
			}
			if !strings.Contains(err.Error(), "declares no schema function") {
				t.Errorf("error = %v, want it to name the missing shape", err)
			}

			after, readErr := os.ReadFile(path)
			if readErr != nil {
				t.Fatal(readErr)
			}
			if string(after) != source {
				t.Error("the file was modified on a refusal; a refused pass must change nothing")
			}
		})
	}
}
